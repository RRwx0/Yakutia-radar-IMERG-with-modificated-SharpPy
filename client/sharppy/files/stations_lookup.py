# ------------------------------------------------------------ координаты
_DOT = re.compile(r'^\(?\s*(-?\d{1,3}(?:\.\d+)?)\s*[,;\s]\s*'
                  r'(-?\d{1,3}(?:\.\d+)?)\s*\)?$')
_COMMA = re.compile(r'^\(?\s*(-?\d{1,3}(?:,\d+)?)\s*[;\s]\s*'
                    r'(-?\d{1,3}(?:,\d+)?)\s*\)?$')


def parse_coords(text):
    """(62.0, 129.7) -> (62.0, 129.7). Не координаты — None.

    Принимает точку как десятичный знак: «62.0, 129.7», «62.0 129.7»,
    со скобками и без. И запятую, если между числами точка с запятой
    или пробел: «62,0; 129,7». Долготу 180-360 переводит в -180..180.
    """
    s = (text or '').strip()
    if not s:
        return None
    m = _DOT.match(s) or _COMMA.match(s)
    if not m:
        return None
    lat = float(m.group(1).replace(',', '.'))
    lon = float(m.group(2).replace(',', '.'))
    if lon > 180:
        lon -= 360
    if not (-90 <= lat <= 90 and -180 <= lon <= 180):
        return None
    return lat, lon


def point_entry(lat, lon):
    """Точка по координатам в том же виде, что и станции списка."""
    sid = f'{lat:.2f}_{lon:.2f}'
    return (sid, f'Точка {lat:.2f}, {lon:.2f}', lat, lon)


